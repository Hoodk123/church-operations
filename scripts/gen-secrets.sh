#!/bin/sh
# Creates .env with strong random secrets. Run once from the repo root:
#     bash scripts/gen-secrets.sh            (create .env, refuse if exists)
#     bash scripts/gen-secrets.sh --force    (overwrite anyway)
# The output is never printed back; open .env yourself if you need a value.
set -eu

cd "$(dirname "$0")/.."
TARGET=.env

if [ -f "$TARGET" ] && [ "${1:-}" != "--force" ]; then
  echo "ERROR: $TARGET already exists. Refusing to overwrite." >&2
  echo "   (intentionally keep it: run 'bash scripts/gen-secrets.sh --force' to overwrite)" >&2
  exit 1
fi

rand() {
  # 48 hex characters (192 bits) from the OS random source. Works in WSL,
  # Git-for-Windows and plain Linux; no third-party tool required.
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 24
  else
    head -c 96 /dev/urandom | od -An -tx1 | tr -d ' \n' | cut -c1-48
  fi
}

POSTGRES_DB_VALUE=church
POSTGRES_USER_VALUE=church_owner

if [ -f "$TARGET" ]; then
  # --force: keep the operator-chosen DB name and TX/ENV, but reroll the passwords.
  POSTGRES_DB_VALUE=$(sed -n 's/^POSTGRES_DB=//p' "$TARGET")
  POSTGRES_USER_VALUE=$(sed -n 's/^POSTGRES_USER=//p' "$TARGET")
fi

cat > "$TARGET" <<EOF
# Generated by scripts/gen-secrets.sh on $(date +%F). NEVER COMMIT THIS FILE.
# Uses fake-but-strong random secrets; passwords printed only here, once.

# Church environment switch. scripts/db-reset-dev.sh refuses to wipe the
# database unless this is exactly "dev".
CHURCH_ENV=dev

# Names (no secrets):
POSTGRES_DB=$POSTGRES_DB_VALUE
POSTGRES_USER=$POSTGRES_USER_VALUE
EOF
# Appending passwords separately keeps them in a narrow block so a spot-read
# sees them together and can be checked for accidental hand-edits quickly.
cat >> "$TARGET" <<EOF

# Secrets (regenerated on --force):
# Strong randomness, 24+ characters, never used anywhere else.
POSTGRES_PASSWORD=$(rand)
CHURCH_APP_PASSWORD=$(rand)
EOF

chmod 600 "$TARGET"

echo "OK: wrote $TARGET with fresh random secrets (mode 600)."
echo "It is git-ignored. Never copy its contents into chat, tickets or screenshots."
